package org.ritika.cognitbackend.dto.request;

import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class RegisterRequest {

    @NotBlank(message = "Email is required")
    @Email(message = "Invalid email format")
    private String email;

    @NotBlank(message = "Password is required")
    @Size(min = 8, message = "Password must be at least 8 characters")
    private String password;

    @NotBlank(message = "Name is required")
    @Size(min = 2, max = 100, message = "Name must be between 2 and 100 characters")
    private String name;

    // Self-selected at signup. Only SUBSCRIBER/AUTHOR are allowed here —
    // ADMIN can never be granted through registration. Optional; defaults
    // to SUBSCRIBER when omitted.
    @Pattern(regexp = "SUBSCRIBER|AUTHOR", message = "Role must be SUBSCRIBER or AUTHOR")
    private String role;
}
